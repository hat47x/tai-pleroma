package main

import (
	"fmt"
	"os"
	"path/filepath"
)

// Review files are new local evidence, never replacements for source material.
func writeNewReviewFile(path string, raw []byte) error {
	file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0600)
	if err != nil {
		return err
	}
	if _, err := file.Write(raw); err != nil {
		_ = file.Close()
		return err
	}
	return file.Close()
}

func requireNewReviewPath(path string) error {
	if _, err := os.Lstat(path); err == nil {
		return fmt.Errorf("review output already exists: %s", path)
	} else if !os.IsNotExist(err) {
		return err
	}
	return nil
}

func saveReviewArtifact(receipt RunReceipt, raw []byte, path string) error {
	if !receipt.Passed {
		return fmt.Errorf("cannot save a review artifact from a failed reference run")
	}
	// Validate the generated bytes before creating the output, then independently
	// re-read the saved file. Neither step grants approval or durable storage.
	if verification := Verify(receipt); !verification.Passed {
		return fmt.Errorf("invalid run: %s", verification.Reason)
	}
	if artifactDigest(raw) != receipt.Components.ReviewArtifact.ArtifactDigest {
		return fmt.Errorf("artifact bytes differ from the run receipt")
	}
	if err := writeNewReviewFile(path, raw); err != nil {
		return err
	}
	if verification := VerifyArtifact(receipt, path); !verification.Passed {
		return fmt.Errorf("saved artifact did not verify: %s", verification.Reason)
	}
	return nil
}

func BuildOwnerPacketWithArtifact(receipt RunReceipt, path string) (OwnerPacket, error) {
	packet, err := BuildOwnerPacket(receipt)
	if err != nil {
		return OwnerPacket{}, err
	}
	if verification := VerifyArtifact(receipt, path); !verification.Passed {
		return OwnerPacket{}, fmt.Errorf("review artifact did not verify: %s", verification.Reason)
	}
	absolute, err := filepath.Abs(path)
	if err != nil {
		return OwnerPacket{}, err
	}
	packet.Evidence = append(packet.Evidence, absolute)
	packet.ArtifactBytesVerified = true
	return packet, nil
}
